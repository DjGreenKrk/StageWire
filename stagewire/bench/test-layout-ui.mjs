// Test układu: przesuwanie węzła jest krokiem cofania, układ zapisuje się w projekcie.
import { createServer } from 'vite';
import { chromium } from 'playwright-core';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const server = await createServer({ root: path.join(root, 'web'), configFile: false, logLevel: 'error', server: { port: 5196, strictPort: true, fs: { allow: [root] } } });
await server.listen();
const browser = await chromium.launch({ channel: 'msedge', headless: false, args: ['--window-size=1400,900'] });
const checks = []; const check = (n, ok, i) => { checks.push({ name: n, ok }); console.log(`${ok ? 'OK  ' : 'FAIL'} ${n}${i !== undefined ? ' — ' + JSON.stringify(i) : ''}`); };
const page = await (await browser.newContext({ viewport: { width: 1366, height: 768 } })).newPage();
page.on('pageerror', (e) => console.log('BŁĄD STRONY', String(e).slice(0, 200)));
await page.goto('http://localhost:5196/editor.html?new=1'); await page.waitForFunction(() => window.__editor?.ready);
const E = (fn, arg) => page.evaluate(fn, arg);
await E(() => window.__editor.look(0, 40, 1)); await page.click('#cat-list button[data-cat="camera_sdi"]');
const [id] = await E(() => Object.keys(window.__editor.nodes()));
const pos = () => E((i) => ({ ...window.__editor.nodes()[i] }), id);
const saved = () => E((i) => Object.values(window.__editor.store.state.views?.viw_main?.nodes ?? {}).find((n) => n.instanceId === i), id);
const p0 = await pos();
check('dodane urządzenie ma zapisaną pozycję w projekcie', JSON.stringify(await saved()) === JSON.stringify({ instanceId: id, x: p0.x, y: p0.y }), { p0, s: await saved() });
await E((i) => window.__editor.look(window.__editor.nodes()[i].x + 100, window.__editor.nodes()[i].y + 40, 1), id);
const hd = await E((i) => window.__editor.nodeScreen(i).header, id);
await page.mouse.move(hd[0], hd[1]); await page.mouse.down(); await page.mouse.move(hd[0] + 150, hd[1] + 90, { steps: 8 }); await page.mouse.up();
const p1 = await pos();
check('przeciągnięcie zmienia pozycję i zapisuje ją w projekcie', p1.x > p0.x + 100 && (await saved()).x === p1.x, { p0, p1 });
await page.keyboard.press('Control+z');
const p2 = await pos();
check('Ctrl+Z przywraca poprzednią pozycję', p2.x === p0.x && p2.y === p0.y, p2);
await page.keyboard.press('Control+y');
const p3 = await pos();
check('Ctrl+Y ponawia przesunięcie', p3.x === p1.x && p3.y === p1.y, p3);
await page.keyboard.press('Control+z'); await page.keyboard.press('Control+z');
check('drugie cofnięcie usuwa dodanie urządzenia', (await E(() => window.__editor.counts().devices)) === 0);
await browser.close(); await server.close();
console.log(`\n${checks.filter((c) => c.ok).length}/${checks.length} kontroli`);
process.exit(checks.every((c) => c.ok) ? 0 : 1);
