// Test katalogu urządzeń w edytorze: wyszukiwanie, dodanie, połączenie gestem, typ kabla. Zrzut: %TEMP%/sw-katalog.png
import { createServer } from 'vite';
import { chromium } from 'playwright-core';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const server = await createServer({ root: path.join(root, 'web'), configFile: false, logLevel: 'error', server: { port: 5194, strictPort: true, fs: { allow: [root] } } });
await server.listen();
const browser = await chromium.launch({ channel: 'msedge', headless: false, args: ['--window-size=1400,900'] });
const checks = []; const check = (n, ok, i) => { checks.push({ name: n, ok }); console.log(`${ok ? 'OK  ' : 'FAIL'} ${n}${i !== undefined ? ' — ' + JSON.stringify(i) : ''}`); };
const page = await (await browser.newContext({ viewport: { width: 1366, height: 768 } })).newPage();
page.on('pageerror', (e) => console.log('BŁĄD STRONY', String(e).slice(0, 200)));
await page.goto('http://localhost:5194/editor.html?new=1'); await page.waitForFunction(() => window.__editor?.ready);
const n = () => page.$$eval('#cat-list button[data-cat]', (b) => b.length);
check('katalog pokazuje 22 urządzenia (14 ogólnych + 8 Blackmagic)', (await n()) === 22);
await page.fill('#catalog input', 'oswietlenie'); check('wyszukiwanie bez polskich znaków: 2 wyniki', (await n()) === 2);
await page.fill('#catalog input', 'sdi'); const sdi = await page.$$eval('#cat-list button[data-cat]', (b) => b.map((x) => x.dataset.cat));
check('wyszukiwanie „sdi” zawiera kamerę i mikser', sdi.includes('camera_sdi') && sdi.includes('video_switcher'), sdi);
await page.fill('#catalog input', '');
await page.evaluate(() => window.__editor.look(0, 100, 1));
await page.click('#cat-list button[data-cat="camera_sdi"]');
await page.evaluate(() => window.__editor.look(430, 100, 1));
await page.click('#cat-list button[data-cat="video_switcher"]');
await page.evaluate(() => window.__editor.look(215, 100, 1));
const ids = await page.evaluate(() => Object.keys(window.__editor.nodes()));
check('dodano 2 urządzenia z poprawnymi portami', ids.length === 2);
const a = await page.evaluate((i) => window.__editor.portScreen(i, 'prt_sdiout'), ids[0]);
const b = await page.evaluate((i) => window.__editor.portScreen(i, 'prt_sdiin3'), ids[1]);
await page.mouse.move(a[0], a[1]); await page.mouse.down(); await page.mouse.move(b[0], b[1], { steps: 12 });
await page.screenshot({ path: path.join(process.env.TEMP, 'sw-katalog.png') });
await page.mouse.up();
const st = await page.evaluate(() => { const s = window.__editor.store.state; return { cnx: Object.values(s.connections), cab: Object.values(s.cables), issues: window.__editor.issues() }; });
check('połączenie kamera → SDI IN 3 utworzone', st.cnx.length === 1 && st.cnx[0].to.portId === 'prt_sdiin3', st.cnx.length);
check('typ kabla dobrany automatycznie: SDI', st.cab[0]?.cableTypeKey === 'std/cable-sdi', st.cab[0]);
check('bez uwag walidacji', st.issues === 0, st.issues);
await page.screenshot({ path: path.join(process.env.TEMP, 'sw-katalog-po.png') });
await browser.close(); await server.close();
console.log(`\n${checks.filter((c) => c.ok).length}/${checks.length} kontroli`);
process.exit(checks.every((c) => c.ok) ? 0 : 1);
